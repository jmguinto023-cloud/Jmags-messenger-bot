#!/usr/bin/env python3
"""Build knowledge/prices.json from JMAGs-PriceList-2026.xlsx plus the owner-confirmed
TV backlight / LCD modification prices. Owner-confirmed values WIN; conflicts are listed in the file.
Usage: python3 scripts/build-prices.py [path/to/JMAGs-PriceList-2026.xlsx]"""
import json, re, sys, os, openpyxl

SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', '..', 'JMAGs-PriceList-2026.xlsx')
OUT = os.path.join(os.path.dirname(__file__), '..', 'knowledge', 'prices.json')

# Owner-confirmed (Jm, memory) - these are what the bot quotes.
OWNER = {
  'lcdMod': {32: 2500, 40: 4500, 43: 5000, 50: 6500, 55: 8500, 60: 9500, 65: 9500, 70: 12500, 75: 14000},
  'backlight': {32: 2500, 40: 4000, 43: 4500, 50: 5500, 55: 8500, 60: 9000, 65: 9500, 70: 12000, 75: 16000},
  'backlight85': {'other': 22000, 'premium': 28000, 'premiumBrands': ['samsung', 'sony', 'sharp', 'lg', 'hisense', 'devant']},
}
KEYS = [('Palit LCD', 'newLcd'), ('Backlight - EDGE', 'backlightEdge'), ('Backlight - Round', 'backlightRound'),
        ('LCD Repair', 'lcdMod'), ('MotherBoard - Smart', 'motherboardSmart'), ('MotherBoard - Basic', 'motherboardBasic'),
        ('Power Supply - Smart', 'powerSupplySmart'), ('Power Supply - Basic', 'powerSupplyBasic'), ('Rebonding', 'rebonding')]

ws = openpyxl.load_workbook(SRC, data_only=True)['Prices']
title = ws.cell(1, 1).value
xlsx, warranty, size = {}, {}, None
for r in ws.iter_rows(min_row=4, values_only=True):
    if r[1]:
        m = re.match(r'(\d+)', str(r[1])); size = int(m.group(1)) if m else size
    desc = str(r[2] or '')
    key = next((k for p, k in KEYS if p.lower() in desc.lower()), None)
    if not key or size is None: continue
    warranty.setdefault(key, {})[size] = r[6]
    if isinstance(r[3], (int, float)): xlsx.setdefault(key, {})[size] = int(r[3])

conflicts = []
for s, v in OWNER['lcdMod'].items():
    x = xlsx.get('lcdMod', {}).get(s)
    if x != v: conflicts.append({'item': 'LCD modification', 'size': s, 'xlsx': x, 'owner': v, 'used': v})
if 85 in xlsx.get('lcdMod', {}):
    conflicts.append({'item': 'LCD modification', 'size': 85, 'xlsx': xlsx['lcdMod'][85], 'owner': None, 'used': None, 'note': 'not quoted; hand off to Ivan'})
for s, v in OWNER['backlight'].items():
    e, rd = xlsx.get('backlightEdge', {}).get(s), xlsx.get('backlightRound', {}).get(s)
    if v not in (e, rd): conflicts.append({'item': 'Backlight', 'size': s, 'xlsxEdge': e, 'xlsxRound': rd, 'owner': v, 'used': v})
e, rd = xlsx['backlightEdge'].get(85), xlsx['backlightRound'].get(85)
conflicts.append({'item': 'Backlight', 'size': 85, 'xlsxEdge': e, 'xlsxRound': rd, 'owner': '22000 other / 28000 premium brands', 'used': 'owner', 'note': 'xlsx splits by panel type, owner splits by brand'})
for s in sorted(set(xlsx.get('backlightRound', {})) - set(OWNER['backlight']) - {85}):
    conflicts.append({'item': 'Backlight', 'size': s, 'xlsxRound': xlsx['backlightRound'][s], 'owner': None, 'used': None, 'note': 'size only in xlsx; bot hands off'})

# Preliminary low-high per size across every xlsx row (same basis the old PRICE_RANGE used).
rng = {}
for k, rows in xlsx.items():
    for s, p in rows.items():
        lo, hi = rng.get(s, (p, p)); rng[s] = (min(lo, p), max(hi, p))

out = {
  'source': os.path.basename(SRC), 'sourceTitle': title,
  'note': 'Generated by scripts/build-prices.py. lcdMod/backlight/backlight85 = owner-confirmed and quoted; xlsx = reference only.',
  'lcdMod': OWNER['lcdMod'], 'backlight': OWNER['backlight'], 'backlight85': OWNER['backlight85'],
  'priceRange': {s: list(rng[s]) for s in sorted(rng)},
  'xlsx': {k: dict(sorted(v.items())) for k, v in xlsx.items()},
  'warranty': {k: dict(sorted(v.items())) for k, v in warranty.items()},
  'transpo': {'1-50km': 500, '50-80km': 1500},
  'conflicts': conflicts,
}
with open(OUT, 'w') as f: json.dump(out, f, indent=1, ensure_ascii=False); f.write('\n')
print(f'wrote {OUT}; {len(conflicts)} conflicts')
for c in conflicts: print(' ', c)
